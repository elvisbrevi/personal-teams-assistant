/// How the remote endpoint treats a tool; anything not listed is denied.
pub(super) fn tool(name: &str) -> Remote {
    TOOLS
        .iter()
        .find(|(tool, _)| *tool == name)
        .map_or(Denied(UNCLASSIFIED), |(_, remote)| *remote)
}

